#!/usr/bin/env python3
import hashlib, os, re, sys
from _selftest_lib import T, run, scratch
t = T("send_log selftest"); d = scratch("send_log")
REAL_LOG = "/workspace/v608build/SEND-LOG.md"; real_before = os.path.exists(REAL_LOG)
log = os.path.join(d, "SEND-LOG.md"); snapf = os.path.join(d, "CURRENT-SNAP.txt")
open(snapf, "w").write("snap=snap-test-0000MDT\npaste_1b_md5=317e91ce86f073c961f8169183d2bbd3\n")
ptr = hashlib.md5(open(snapf, "rb").read()).hexdigest()
a, b, c = (os.path.join(d, n) for n in ("a.png", "b.png", "never.png"))
open(a, "wb").write(b"\x89PNG fake A"); open(b, "wb").write(b"\x89PNG fake B"); open(c, "wb").write(b"\x89PNG never sent")
ma, mb, mc = (hashlib.md5(open(p, "rb").read()).hexdigest() for p in (a, b, c))
L = ["--log", log, "--snap-file", snapf]

rc, o = run("send_log.py", *L, "add", "--file", a, "--file", b, "--to", "Maxwell", "--note", "tile 6 | tree grounded")
t.ok(rc == 0 and o.count("LOGGED") == 2, "add two files -> exit 0, 2 LOGGED", o)
txt = open(log).read(); rows = [l for l in txt.splitlines() if l.startswith("| 20")]
t.ok(len(rows) == 2, "two rows written, one per image", txt)
t.ok(ma in rows[0] and mb in rows[1], "full 32-char md5 per row", txt)
t.ok(all("snap-test-0000MDT" in r and ptr in r for r in rows), "rows carry snap name + full pointer md5 of CURRENT-SNAP.txt", txt)
t.ok(all(re.search(r"\| 20\d\d-\d\d-\d\d \d\d:\d\d:\d\d M[SD]T \|", r) for r in rows), "timestamp in Mountain time with MST/MDT label", txt)
t.ok(all(os.path.abspath(a) in rows[0] for _ in [0]), "absolute file path logged", txt)
t.ok("tile 6 \\| tree grounded" in rows[0], "pipe in note escaped", txt)
t.ok(all(l.startswith("**Quartermaster:**") for l in txt.splitlines()[:2]), "log header lines carry **Quartermaster:** prefix", txt)
rc, o = run("send_log.py", *L, "check", a)
t.ok(rc == 1 and o.startswith("SENT 1 time") and ma in o and "Maxwell" in o, "check sent file -> SENT with when, exit 1", o)
t.ok("tile 6 | tree grounded" in o, "check round-trips the escaped note", o)
rc, o = run("send_log.py", *L, "check", c)
t.ok(rc == 0 and o.startswith("NOT SENT"), "check unsent file -> NOT SENT, exit 0", o)
rc, o = run("send_log.py", *L, "check", mb)
t.ok(rc == 1 and "SENT 1" in o, "check by bare md5 works", o)
rc, o = run("send_log.py", *L, "add", "--file", a, "--to", "Maxwell", "--note", "resend")
t.ok(rc == 0 and "ALREADY SENT" in o, "re-adding a sent md5 warns ALREADY SENT (still logs)", o)
rc, o = run("send_log.py", *L, "check", a)
t.ok("SENT 2 time" in o, "check counts both sends", o)
rc, o = run("send_log.py", *L, "list")
t.ok(rc == 0 and "3 row(s)" in o, "list prints all 3 rows", o)
n_before = open(log).read().count("\n")
rc, o = run("send_log.py", *L, "add", "--file", os.path.join(d, "missing.png"), "--to", "Maxwell")
t.ok(rc == 2 and open(log).read().count("\n") == n_before, "missing file -> exit 2, nothing appended", o)
rc, o = run("send_log.py", "--log", os.path.join(d, "empty.md"), "list")
t.ok(rc == 0 and "no rows" in o, "list on absent log -> no rows, exit 0", o)
# real CURRENT-SNAP.txt is read correctly (log still goes to scratch)
rc, o = run("send_log.py", "--log", os.path.join(d, "real-snap-log.md"), "add", "--file", c, "--to", "Maxwell", "--note", "real snap read")
rt = open(os.path.join(d, "real-snap-log.md")).read()
live_ptr = hashlib.md5(open("/workspace/v608build/CURRENT-SNAP.txt", "rb").read()).hexdigest()
live_snap = [l.split("=", 1)[1].strip() for l in open("/workspace/v608build/CURRENT-SNAP.txt") if l.startswith("snap=")][0]
t.ok(rc == 0 and live_snap in rt and live_ptr in rt, f"real CURRENT-SNAP.txt read ({live_snap}, pointer {live_ptr[:8]})", rt)
t.ok(os.path.exists(REAL_LOG) == real_before, "real /workspace/v608build/SEND-LOG.md untouched by the self-test")
t.ok(all(os.path.exists(p) for p in (a, b, c, snapf)), "no input file deleted")
print("scratch kept at " + d)
sys.exit(t.done())
